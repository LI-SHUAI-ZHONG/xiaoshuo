function portableOutput(name=''){const p=require('node:path'),f=require('node:fs');const root=p.resolve(process.env.STUDIO_CHECK_OUTPUT||'build/client-v3-browser-evidence');f.mkdirSync(root,{recursive:true});return p.join(root,name);}
const {chromium, expect} = require(process.env.PLAYWRIGHT_MODULE||'@playwright/test');
const fs = require('node:fs');
const out = portableOutput();
(async () => {
  const browser = await chromium.launch({headless:true,executablePath:(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE||undefined)});
  const page = await browser.newPage({viewport:{width:1440,height:960}});
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  page.on('console', m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto('http://127.0.0.1:18765/#/home');
  await expect(page.getByRole('heading',{name:'开始今天的创作'})).toBeVisible();
  await expect(page.getByRole('navigation',{name:'一级导航'}).getByRole('link')).toHaveCount(7);
  await expect(page.locator('#statusConnection')).toContainText('后端已连接');
  await page.screenshot({path:out+'/home-desktop.png',fullPage:true});
  await page.locator('#btnThemeToggle').click();
  await expect(page.locator('html')).toHaveAttribute('data-theme','light');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme','light');
  await page.keyboard.press('Control+j');
  await expect(page.locator('#bottomPanel')).toBeVisible();
  await page.reload();
  await expect(page.locator('#bottomPanel')).toBeVisible();
  await page.keyboard.press('Control+k');
  await expect(page.locator('#searchOverlay')).toBeVisible();
  await page.locator('#searchInput').fill('玄幻');
  await expect(page.locator('#searchResults')).toContainText('玄幻');
  await page.keyboard.press('Escape');
  await page.keyboard.press('Control+j');
  await page.locator('#btnThemeToggle').click();
  await page.setViewportSize({width:390,height:844});
  await page.reload();
  await expect(page.getByRole('heading',{name:'开始今天的创作'})).toBeVisible();
  const dimensions = await page.evaluate(()=>({body:document.body.scrollWidth,viewport:innerWidth,tabY:document.querySelector('#activityBar').getBoundingClientRect().top}));
  await page.screenshot({path:out+'/home-mobile.png',fullPage:true});
  if(dimensions.body>dimensions.viewport)throw new Error('Mobile horizontal overflow '+JSON.stringify(dimensions));
  if(errors.length)throw new Error(errors.join('\n'));
  fs.writeFileSync(out+'/browser-shell.json',JSON.stringify({passed:true,errors,dimensions},null,2));
  console.log(JSON.stringify({passed:true,errors,dimensions}));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
