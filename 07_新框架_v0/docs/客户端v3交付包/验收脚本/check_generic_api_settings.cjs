function portableOutput(name=''){const p=require('node:path'),f=require('node:fs');const root=p.resolve(process.env.STUDIO_CHECK_OUTPUT||'build/client-v3-browser-evidence');f.mkdirSync(root,{recursive:true});return p.join(root,name);}
const {chromium,expect}=require(process.env.PLAYWRIGHT_MODULE||'@playwright/test');
const fs=require('node:fs');
const out=portableOutput();
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE||undefined)});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],external=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(/^https?:/.test(r.url())&&!r.url().startsWith('http://127.0.0.1:18765/'))external.push(r.url());});
  await page.goto('http://127.0.0.1:18765/#/settings');
  await expect(page.locator('#settingsForm')).toBeVisible();
  await expect(page.locator('#modelProvider')).toHaveCount(0);
  await expect(page.locator('#modelBaseUrl')).toHaveValue('');
  await expect(page.locator('#modelName')).toHaveValue('');
  await expect(page.locator('#apiKeyEnv')).toHaveValue('NW_API_KEY');
  await expect(page.locator('#settingsForm')).not.toContainText('Ollama');
  let previews=0;page.on('request',r=>{if(r.url().endsWith('/api/config/preview'))previews++;});
  await page.locator('#previewConfig').click();expect(previews).toBe(0);
  await page.locator('#modelBaseUrl').fill('https://writing.example.test/v1');
  await page.locator('#modelName').fill('author-model');
  await page.locator('#apiKeyEnv').fill('MY_WRITING_API_KEY');
  await page.locator('#stageModelSettings summary').click();
  await page.locator('[data-stage-model=review]').fill('review-model');
  await page.locator('#previewConfig').click();
  await expect(page.locator('#drawerBody')).toContainText('openai_compat');
  await expect(page.locator('#drawerBody')).not.toContainText('LOCAL_LEGACY_ONLY');
  await expect(page.locator('#drawerBody')).not.toContainText('11434');
  await expect(page.locator('#drawerBody')).not.toContainText('top_k');
  await page.locator('#drawer [data-close-drawer]').click();
  const saved=page.waitForResponse(r=>r.url().endsWith('/api/config/save'));
  await page.locator('#settingsForm button[type=submit]').click();
  const response=await saved;expect(response.ok()).toBe(true);
  const body=(await response.json()).status.current;
  expect(body.provider).toBe('openai_compat');expect(body.model).toBe('author-model');
  expect(body.stage_models.review.model).toBe('review-model');
  expect(body.params.top_k).toBeUndefined();
  await expect(page.locator('#settingsForm')).toContainText('连接未验证');
  await page.reload();await expect(page.locator('#modelBaseUrl')).toHaveValue('https://writing.example.test/v1');
  await expect(page.locator('#modelName')).toHaveValue('author-model');
  await expect(page.locator('#apiKeyEnv')).toHaveValue('MY_WRITING_API_KEY');
  await page.screenshot({path:out+'/通用API设置.png'});
  expect(external).toEqual([]);expect(errors).toEqual([]);
  const result={passed:true,empty_fields_blocked:true,no_local_defaults:true,saved_api:true,reload_preserved:true,no_model_calls:true,errors};
  fs.writeFileSync(out+'/通用API设置验收.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
