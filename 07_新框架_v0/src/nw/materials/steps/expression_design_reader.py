MATERIAL = """【表达设计的节奏、主题和读者资料】
把上游已有的节奏、主题作用和读者预期落实到本场可见动作、信息顺序、段落及检查点。

### 板块62 节奏控制#场景内快慢交替
【定义】单个场景内部的快慢变化。
【判定标准】规则**：
- 场景内不能全程匀速
- 建立阶段：中速
- 升级阶段：加速
- 高潮阶段：高速
- 
【本步用法】
按本场已确认的事件分配节奏。建立段让读者掌握现场，升级段沿动作和结果加快，已承担余波的段落放缓，留给可见后果和人物反应。项目确有缓冲任务时，按已有氛围、感知和微型推进处理。随已定语体用快段的短句、慢段的观察和停顿交代变化。
### 板块62 节奏控制#空隙
【定义】场景间的节奏间隙。
【设计指令】场景间的节奏间隙。
【本步用法】
用已有空间、时间或情绪变化表现场间过渡。
### 板块62 节奏控制#静默时刻
【定义】完全无外部冲突的深度体验瞬间。
【设计指令】完全无外部冲突的深度体验瞬间。
【本步用法】
依当前视角实际感受安排已确认的静默节点。
### 板块62 节奏控制#情绪承接
【定义】章节之间的情绪连贯性。
【判定标准】规则**：
- 上一章结尾的情绪在下一章开头被承接（不是被忽略）
- 情绪可以变化但不能断档
- 轻章到重章
【同版补用原文｜110.3 第107107、107115行】
- 从安宁到不安：光线变暗、声音变少、温度变低
**写作规则**：氛围渐变用于节奏变化（轻章到重章、重章到空章的过渡），让读者在感知上逐步进入新状态。
【本步用法】
结合前章确有的反应与本场已选光线、声音或身体感受，设计仍能察觉的旧情绪。由轻章转重章时，从同一处可感细节引出新的不安或压力，保持已有来由。
### 板块62 节奏控制#情绪断裂
【定义】情绪承接不足导致的读者体验断裂。
【判定标准】规则**：避免情绪断裂
【本步用法】
用实际前因和可观察反应串接不同情绪。
### 板块63 主题系统#主题表现方式
【定义】主题通过行动呈现，而非通过旁白陈述。
【设计指令】主题通过行动呈现，而非通过旁白陈述。
【本步用法】
给已有主题所对应的实际行动和结果设计表现。
### 板块63 主题系统#价值观锚点
【定义】故事中明确表达“什么是对的”“什么是值得的”的时刻。
【设计指令】故事中明确表达“什么是对的”“什么是值得的”的时刻。
【本步用法】
在当前视角下表现已设计的价值选择及其实际代价。
### 板块64 读者情感#读者情绪拐点设计
【定义】情绪方向发生变化的节点。
【判定标准】规则**：拐点是最需要事件支撑的
【本步用法】
用本场可见的真实事件表现已经分配的情绪转向。
### 板块64 读者情感#读者情绪恢复期
【定义】高强度情绪后给读者的恢复时间。
【指令】高强度情绪后给读者的恢复时间。
【本步用法】
依既定压力和结果给本场安排能够缓和或消化的具体表现。
### 板块65 读者认知#读者注意力引导
【定义】让读者关注作者想让关注的内容。
【判定标准】规则**：读者注意力的方向由写作决定
【本步用法】
从已有对象及动作安排读者注意的次序与落点。
### 板块65 读者认知#读者阅读速度控制
【定义】让读者在某些地方读得快、在某些地方读得慢。
【判定标准】读者阅读速度控制是否在文中得到体现，读者能否感知到该技法的效果
【本步用法】
按实际任务给快段和慢段分配动作与观察，检查是否呈现预定速度。
### 板块65 读者认知#读者遗忘机制
【定义】读者会忘记之前的信息。
【设计指令】读者会忘记之前的信息。
【本步用法】
本场已安排提醒旧信息时，使用能由现有行动或对象自然带出的线索。
### 板块66 读者记忆#读者重读惊喜设计
【定义】重读时发现第一次没注意到的细节。
【设计指令】重读时发现第一次没注意到的细节。
【本步用法】
本场已安排可以重读辨认的细节时，按当时可知范围表现它的实际形态。"""
