"""场景设计步骤所用的《资料库》原文和本步用法。"""

MATERIAL = """【场景设计的资料】
只用于本场已选事件和行动涉及的人物及信息。
采用受限视角时，从已选人物中明确一位观察者。场卡写明能从当时感知、此前所知或已收到消息知道的内容，并标出可以向读者披露到哪里。
采用板块151且本场实际改变身份、行为许可或社会责任时，将仍有效的身份范围写入该事件的 before_state。属性用 identity_status:职位、机构或其他已定范围；值含 identity、permissions、social_expectations，取已有前值。首次确无前值时该属性为 null。身份揭示、误信或表面说辞分别在本场视角与披露范围中说明当事人、所知和可见证据。

### 1.3_次要配角
【指令】
次要配角出场规则：
- 每次出场完成至少一项具体功能（传递信息/制造冲突/提供资源/展示世界）后即可退场
- 每次出场不超过1个场景
- 不需要独立弧光，但单点变化须在出场场景中可见
【本步用法】
依人物卡的出场功能，将本次出场承担的具体作用及已有的单点变化落实到本场的任务和结果。
### 1.4_背景角色
【指令】
背景角色出场规则：
- 可在任何场景中以“存在”的方式出场，不需要名字（可用“一个老人/店小二/巡逻守卫”指代）
- 不需要对话，若对话则不超过1句且不携带情节信息
- 功能仅为“让场景不空”或“让世界有密度”
- 出场不占据单独段落，融入环境描写或动作背景中
- 同一场景中背景角色不超过3人
【本步用法】
采用这类角色时从已有场景确定环境功能，把他放在正在发生的环境动作中。遵守原文每场不超过3人，台词至多一句，内容只表现当场氛围。
### 1.5_缺席者
【指令】
- 通过对话、信件、回忆等间接方式被提及
- 每次被提及释放1条信息，不重复释放同一条
【本步用法】
本场已有该项提及时，用剧情分配的载体和新信息确定本场允许披露的内容。剧情已将第三次提及后的提示分配到本场时，一并纳入披露安排。
### 5.1_亲缘关系
【指令】
**写作规则**：亲缘关系的变化不通过切断来完成，而通过重新定义来完成。“我依然是你儿子，但我不再按你安排的路走。”每一次重大变化都必须对应一个具体场景。
【本步用法】
本场已选的事件涉及重大亲缘变化时，用现有事件和动作落实关系怎样被重新定义，写入本场结果。
### 7.1_情感触发条件
【定义】
每个情感必须有具体的触发事件。触发事件必须被读者感知，不能是“他忽然悲伤起来”这种无因情感。
【本步用法】
本场安排情感变化时，将其触发落实在已选事件或行动及当前可披露范围内。
### 7.9_情感密度控制
【定义】
不同节奏类型章节的情感密度不同：
【写作指令】
- 空章：1-2情感点，深度描写（一个情感贯穿整章）
【同版补用原文｜《资料库》第198705–198708、198711行】
- 重章：情感密度3-5个情感点，以驱动情感和冲突情感为主
- 中章：情感密度2-4个情感点，各类型均衡
- 轻章：情感密度1-2个情感点，以存在情感和关系情感为主
- 空章：情感密度1-2个情感点，深度描写，单情感贯穿全章
情感点定义：一个可以被读者识别和命名的情感触发-反应单元（如“他看到信时手抖了一下”算1个情感点）。
【本步用法】
四种章型按实际已确认的章任务使用155.3的相应密度。把负责各点的事件、人物反应和篇章作用分给实际场次。同一个情感单元跨场延续时，安排承接点并交代沿用的触发。
### 155.3_节奏类型与情感密度的强制匹配
【同版补用原文｜《资料库》第198705–198708、198711行】
- 重章：情感密度3-5个情感点，以驱动情感和冲突情感为主
- 中章：情感密度2-4个情感点，各类型均衡
- 轻章：情感密度1-2个情感点，以存在情感和关系情感为主
- 空章：情感密度1-2个情感点，深度描写，单情感贯穿全章
情感点定义：一个可以被读者识别和命名的情感触发-反应单元（如“他看到信时手抖了一下”算1个情感点）。
【本步用法】
四种章型按实际已确认的章任务使用155.3的相应密度。把负责各点的事件、人物反应和篇章作用分给实际场次。同一个情感单元跨场延续时，安排承接点并交代沿用的触发。
### 9.2_状态化解规则
【指令】
- 重章中至少出现1次状态化解过程，不能只用一句话带过
【本步用法】
当前章已被设计为重章且已有待化解状态时，把化解步骤分配到有相应事件和行动的场景；各场只承接已安排的部分。无待化解状态时的范围待核。
### 9.4_状态事件触发变化规则
【定义】
特定事件导致状态突变。
【指令】
**突变规则**：
- 突变必须有清晰的事件因果链
- 突变不能凭空发生（必须有一个被读者看到的事件）
- 突变后状态需要在新位置上重新稳定
【本步用法】
现有选定事件确会造成突变时，将实际触发和受影响对象的前状态写进 events，保留读者能看到的起因及本场结果。
### 11.3_固化态
【指令】
**写作规则**：固化态资源通常出现在关键节点（探索遗迹、战胜强敌、完成支线），作为对读者的奖励点。获得固化态资源后，其转化过程应被读者看到，而非“跳过转化直接变强”。转化过程的篇幅取决于资源重要性和当前节奏——重要资源至少占200-300字描写，次要资源可在叙述中一笔带过但必须出现。
【本步用法】
已选事件涉及固化资源时，按原文区分资源重要性，给现有场景安排可见的转化过程和篇幅。原文的‘至少200-300字’下限待核。
### 12.9_能量干扰规则
【指令】
**写作规则**：干扰规则创造“不稳定”空间——关键对话或战斗可能在感知盲区发生，暴露角色的真实状态而不被察觉。
【本步用法】
当已选行动利用既有盲区时，在本场披露边界保留各角色实际能察觉的内容。
### 15.2_进阶三阶段
【写作指令】
- 突破期的描写必须有一个“临界点”——某一个瞬间读者知道“他突破成功了”
【本步用法】
本场已承担突破时，按已有进阶结果与事件安排让读者能辨认成败的瞬间。
### 18.3_能量源衰竭
【指令】
**写作规则**：一个正在衰竭的能量源是高风险高回报的场景——角色可能在它彻底枯竭前做最后的获取或领悟。
【本步用法】
本场已选事件与衰竭源有关时，使用既定地点、窗口和动作，写明本场实际风险、可能取得的东西及可观察结果。
### 19.4_例外的验证
【指令】
**写作规则**：验证过程本身可以是一条叙事线——角色试图确认“那个东西是真的特殊，还是我搞错了”。验证过程也是伏笔的展开方式。
【本步用法】
本场已承担例外验证时，将既有验证动作和本场允许揭示的观察结果写入场景卡。
### 28.2_道具功能边界
【指令】
**写作规则**：功能边界必须在道具首次出现时让读者大概感知到范围（“这东西好像能加速修炼”），后续通过使用逐步精确化。没有边界的道具是机械降神，有了边界读者才知道“什么时候该期待什么”。
【本步用法】
场卡记录本场可见的一项功能迹象、触发它的已选行动及本场可披露的界线。有前置明确这是首次出现时安排粗略迹象；后续试用承接已实际显示过的作用，再把本场确认的边界写清。
### 29.2_道具与环境交互
【指令】
**写作规则**：道具与环境的交互创造了“探索场景”——角色需要在特定环境中使用道具，或探索特定环境来激活道具的功能。
【本步用法】
从既定场地说明哪个地点或环境状态使动作生效，观察者站在哪里、能察觉什么、道具实际发生了何种改变。该结果会改变通行或探索时，把变化和接下来的去处留在场卡。
### 30.2_功能边界测试与突破
【指令】
**写作规则**：功能测试和突破的过程本身就是叙事内容，不能一笔带过。读者需要看到角色“试了、失败了、又试了、最终成功了”的过程。
【本步用法】
把已有试验按实际次序交接给正文。记录当次在尝试什么、与前一回不同的条件、可见的受阻或生效结果及能确认的边界。后续测试接当前已证实的结果。
### 30.5_道具失效与转化
【指令】
**写作规则**：道具的失效和转化是其生命史的终点。一个重要道具的失效或转化应该是情感事件——读者为之投入了情感期待，它的终结应有情感分量。
【本步用法】
沿本场已选失效或转化事件，记录最后一次可用作用、造成终止的动作、当场留下的实物和受影响人物的选择。仍有前值留下时交接给后续场景。
### 31.2_地理结构
【指令】
**写作规则**：地理结构在故事进展中逐步展开，不是一开始就全部告诉读者。每到一个新的地理区域，通过角色的探索和感知来展示。
【本步用法】
本场已有进入新区域的事件时，依既定探索路线和人物权限确定实际能展示的地理内容。
### 33.1_阶层划分
【指令】
**写作规则**：阶层划分在第一章就应通过具体场景体现——“杂役走在最边上，内门弟子走在中间，长老走在最前面”。阶层通过空间距离、称谓方式、行为规范等细节被读者感知。
【本步用法】
上游已分配本场体现社会层级时，将已有空间、称谓或行为差异落实到场景。第一章的要求按章范围落实。
### 35.3_半透明
【指令】
- 读者知道规则但不知道边界在哪里
- 读者知道历史片段但不了解全貌
- 读者知道存在某种东西但不清楚它是什么
- 读者知道角色知道什么，不知道角色不知道什么
【本步用法】
用场景卡的 allowed_disclosure 保留本次可见的规则、历史或未知物线索以及具体披露边界。
### 29.3_道具反功能
【同版原文｜《资料库》第55094、55102、197769行】
道具不配合或反向作用的倾向。
**写作规则**：反功能是道具的“不可靠性”，它制造不确定性——读者无法确定“这次使用会不会出问题”。反功能是制造紧张感的工具，也是展示道具“有自我意志”的手段。
读者或角色面对多种可能路径/答案/结果，且当前信息不足以排除其中任何一种时产生的认知状态。不确定性不是"不知道"——未知是信息缺失（"不知道门后有什么"），不确定性是信息存在但不可排他（"知道门后有可能是A/B/C，但无法判断是哪一个"）。
【本步用法】
本场已有反向或不配合风险时，保留前置规则允许的不同结果，明确当前角色凭什么还无法确定。场卡只安排已选行动及生效结果，并留出察觉的时点与付出的代价。"""
