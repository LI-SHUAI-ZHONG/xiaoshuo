MATERIAL = """【状态传播的资料】
使用已经存在的变化根、可行动人物、目标和实际约束。候选传播沿用本步原有的激活条件。传播后果以本项目的实际触发、外部选择、作用对象及前后变化为据。行动窗口或消息暴露有独立依据时才作为代价。

### 20.4_资源生产-消费平衡
【指令】
**写作规则**：资源平衡状态决定势力采取的策略——盈余时扩张，赤字时掠夺或收缩。生态枯竭的叙事起点通常就是资源平衡从盈余转向赤字。
【本步用法】
已有根变化使某势力从盈余转向赤字时，沿用既定势力目标和可行动的人物，将其实际应对、影响的真实对象及可观察后果写入传播候选。
### 27.3_资源稀缺性影响
【指令】
**写作规则**：稀缺性不能是静态设定，应该是动态变化的。当某种资源变得稀缺时，以此为生的人会恐慌，控制它的人权力会膨胀，依赖它的人会绝望。资源的稀缺和丰盈交替，是经济叙事和势力冲突的天然驱动力。
【本步用法】
已有稀缺或丰盈变化根时，从现有依赖关系核对谁受影响。仅在上游有相应的选择与行动时，设计具体对象、候选影响及继续成立的条件。"""
