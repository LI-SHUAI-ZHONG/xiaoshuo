"""动作设计中认知、预期、身份和立场错位原文。"""

MATERIAL = """【角色依据自己的认知行动】
沿用已设事件和每名角色实际知道、推测或相信的内容。用动作、障碍、应对和结果说明错位在当前行动中如何生效。

### 117.1_认知错位
【原文位置】板块117 认知错位 第125129行
**定义**：角色A认为X，角色B认为Y，真相是Z。**类型**：
- A认为B是朋友，B实际是敌人（或相反）
- A认为某事件是这样发生的，实际上是那样发生的
- A认为自己的动机是X，实际深层动机是Y
**写作规则**：认知错位是对话冲突的主要来源——两人说的都是真话，但前提不同。
【本步用法】
依据不同角色对同一问题的不同前提写出各自会怎样回应；真相沿用已有世界设定。
### 117.2_预期错位
【原文位置】板块117 认知错位 第125446行
**定义**：角色期望A发生，实际发生B。**类型**：
- 角色以为会赢，结果输了
- 角色以为对方会理解，结果对方误解
- 角色以为危险来自北方，实际来自南方
**写作规则**：预期错位制造转折和反转。
【本步用法】
以人物既有预期为前置，给出实际不同的结果和可见反应。原件提出错位后的消化阶段，尾句留待补齐。
### 117.5_身份错位
【原文位置】板块117 认知错位 第126401行
**定义**：角色认知的身份与实际身份不一致。**类型**：
- 角色以为自己是A，实际上A只是表象
- 他人以为角色是A，实际上是B
- 角色扮演一个身份久了，开始分不清真假
**写作规则**：身份错位是自我认知错位（板块140）的外部表现——角色用错误的方式感知自己的位置。
【本步用法】
当实际身份与角色认定不同，用受该认定影响的现有选择表现。按现有披露保留身份真相。
### 117.6_立场错位
【原文位置】板块117 认知错位 第126718行
**定义**：角色以为的盟友实际上是敌人，反之亦然。**类型**：
- 一直以为是朋友的人，其实是对方阵营的
- 一直以为是对手的人，其实是站在自己这边的
- 中立者实际上早已站队
**写作规则**：立场错位的揭示是反转的一种形式。
【本步用法】
用已经建立的真实阵营和当事人认知解释其具体决定，并保留已设的反转或后果。"""
