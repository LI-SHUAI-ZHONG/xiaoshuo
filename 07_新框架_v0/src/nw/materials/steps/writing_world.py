MATERIAL = """【正文写作的种族、能力与职业资料】
依照本场已经确认的表现与披露范围写作。

### 36.1_种族类型
【写作指令】
**写作规则**：种族不是在故事中告知的标签，而是通过具体特征被读者感知——一个精灵角色的长耳、长寿、对自然的亲和力，是在出场场景中通过描写和互动逐步呈现的。不同种族之间的区别通过对比展示，而非通过旁白解释。
【本步用法】
采用本场已经确定的特征、互动和对照。
### 36.2_种族基本属性
【指令】
**写作规则**：种族属性差异必须在互动中体现——长寿种族和短寿种族对同一事件的态度不同（精灵觉得“不过十年”，人类觉得“一生已经过了大半”）。属性差异不能被陈述，要通过行为差异被感知。
【本步用法】
本场确有已安排的属性差异时，写它怎样改变角色的判断和行为。
### 38.3_能力边界定义
【指令】
**写作规则**：能力边界必须在能力首次展示时被读者感知。边界的拓展是成长的标志，但每一次拓展都有代价。
【本步用法】
按本场已有能力表现和边界写作，已有代价依当前视角可见的部分体现。
### 39.1_职业类型
【指令】
**写作规则**：职业类型的多样性让世界有生活气息。不是每个人都是修士，大多数人是做着普通工作的普通人。职业类型通过具体人物的日常行为展示，而非通过列表告知读者。
【本步用法】
通过本场已设的工作和日常行动表现职业，原文的修士例子随项目设定使用。
### 39.3_职业与能力关系
【指令】
**写作规则**：职业能力不是标签，而是通过实际工作场景展示的。角色做某件事的方式体现其职业训练。
【本步用法】
写出本场既定的工作过程和体现职业训练的动作。
### 40.1_制造
【指令】
**写作规则**：制造不是“一键合成”，必须有步骤和过程。制造过程的篇幅与产物的价值成正比。
【本步用法】
让已有材料经过本场实际进行的工序，写关键操作怎样形成新物或尚未完成的中间物。
### 40.2_制作
【指令】
**写作规则**：制作过程的呈现是展示角色技能和世界物质基础的方式。每一次制作都是角色能力的验证。
【本步用法】
用本场既定工序和操作反馈表现人物的技能，把成功、偏差或失败落到实际成品状态。
### 40.4_技能升级条件
【指令】
**写作规则**：技能升级必须被读者感知——“他能做之前做不了的东西了”。技能升级的确认通常通过一次成功的制造或挑战性任务来完成。
【本步用法】
本场承担升级的表现时，写出已经安排的作品或挑战，以及可感知的能力差异。
### 40.6_制作-新旧-好坏关系
【指令】
**写作规则**：物品质量通过使用结果展示——好武器在战斗中表现如何，坏武器在关键时刻如何失效。质量差异是角色制造技能的直接证明。
【本步用法】
用本场已有的实际使用结果表现制作物质量。"""
