def _specifications() -> dict[str, dict]:
    specs = {}
    for line in MATERIAL.splitlines():
        before, _, payload = line.partition('｜')
        if not before.isdecimal() or not payload.startswith('{'):
            continue
        raw = json.loads(payload)
        key = raw['id']
        if key in _DESIGN:
            consumers, needs, operation, check = _DESIGN[key]
            specs[key] = {'source': raw['source'], 'target': raw['target'], 'relation': raw['type'],
                          'condition': raw['condition'].removesuffix('；且当前故事明确采用该静态关系'),
                          'needs': needs, 'operation': operation, 'check': check, 'consumers': consumers,
                          'status': 'conditional', 'line': int(before), 'valid_types': tuple(raw['valid_types'])}
    return specs


SPECS = _specifications()
